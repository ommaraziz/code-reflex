pub fn spec_for_path<'a>(path: &Path, specs: &'a [LangSpec]) -> Option<&'a LangSpec> {
    let ext = path.extension()?.to_str()?.to_ascii_lowercase();
    specs.iter().find(|s| s.exts.contains(&ext.as_str()))
}
