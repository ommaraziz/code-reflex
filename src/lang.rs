use std::path::Path;
use tree_sitter::Language;

#[derive(Clone, Copy, PartialEq, Eq, Debug, serde::Serialize)]
pub enum SymbolKind {
    Module,
    Namespace,
    Class,
    Struct,
    Enum,
    Interface,
    Trait,
    Impl,
    Function,
    Method,
    Constant,
    Field,
    Property,
    TypeAlias,
    Variant,
}

impl SymbolKind {
    pub fn as_str(&self) -> &'static str {
        match self {
            SymbolKind::Module => "module",
            SymbolKind::Namespace => "namespace",
            SymbolKind::Class => "class",
            SymbolKind::Struct => "struct",
            SymbolKind::Enum => "enum",
            SymbolKind::Interface => "interface",
            SymbolKind::Trait => "trait",
            SymbolKind::Impl => "impl",
            SymbolKind::Function => "function",
            SymbolKind::Method => "method",
            SymbolKind::Constant => "constant",
            SymbolKind::Field => "field",
            SymbolKind::Property => "property",
            SymbolKind::TypeAlias => "type_alias",
            SymbolKind::Variant => "enum_variant",
        }
    }

}

pub struct LangSpec {
    pub name: &'static str,
    pub exts: &'static [&'static str],
    pub language: Language,
    /// node kind -> symbol kind
    pub symbols: &'static [(&'static str, SymbolKind)],
    /// ancestor node kinds that turn a Function into a Method
    pub method_parents: &'static [&'static str],
    /// node kinds that are enum members
    pub variant_kinds: &'static [&'static str],
    pub string_kinds: &'static [&'static str],
    pub number_kinds: &'static [&'static str],
    pub comment_kinds: &'static [&'static str],
    pub detect_hardcoded: bool,
}

